#!/usr/bin/env python3
"""Writes skills/rive-ui-kit/references/components.md from shared/*.rml and README.md.

The contract of every component (artboard, view model, property ids, list item types,
nested components) is read from the RML, so the skill can't drift from the kit.
The prose per component comes from its README section, when it has one.

Usage: python3 tools/skill_reference.py   (run from the repo root, after ./pull.sh)
"""
import glob
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SHARED = os.path.join(ROOT, "shared")
OUT = os.path.join(ROOT, "skills", "rive-ui-kit", "references", "components.md")

TYPES = {
    "ViewModelPropertyString": "string",
    "ViewModelPropertyNumber": "number",
    "ViewModelPropertyBoolean": "boolean",
    "ViewModelPropertyTrigger": "trigger",
    "ViewModelPropertyColor": "color",
    "ViewModelPropertyList": "list",
    "ViewModelPropertyViewModel": "view model",
    "ViewModelPropertyAssetImage": "image",
    "ViewModelPropertyEnum": "enum",
    "ViewModelPropertySymbolListIndex": "list index (filled in by the list)",
}
# Artboards that only exist to build the Showcase demo
SHOWCASE_ONLY = {"Showcase", "Showcase Section", "Slide", "Tile", "Toolbar", "Sidebar", "Nav Group", "Nav Item"}

HEADER = """# Component reference

Generated by `tools/skill_reference.py` from the kit's RML and README. Do not edit by hand.

- Properties starting with `_` are internal state: read them if a section says so, never set them.
- Triggers (`_pressed`) are the component's events: listen to them in your app.
- Each component has a nested-instance snippet. Replace `X` with your own id prefix (`60000`, then `60001` for the
  next snippet, and so on: ids are unique across the whole document), set `propertyValue` on the properties you
  need and keep every line: a property left out leaves its binds unset.
- Sizing: `hug` suits components with a natural size (Button, Badge, Switch). Components with wrapping text
  (Alert, Accordion, Tooltip) collapse under `hug`: use `instanceWidthScaleType="fill"` or a fixed width.
"""


def load_root():
    tree = ET.parse(os.path.join(SHARED, "99-_root.rml"))
    vms, props_by_id = {}, {}
    for vm in tree.iter("ViewModel"):
        props = []
        for p in vm:
            if p.tag in TYPES:
                prop = {"name": p.get("name"), "type": TYPES[p.tag], "tag": p.tag, "id": p.get("id"),
                        "ref": p.get("viewModelReferenceId"), "items": set()}
                props.append(prop)
                props_by_id[prop["id"]] = prop
        vms[vm.get("id")] = {"name": vm.get("name"), "global": vm.get("viewModelType") == "global",
                             "props": props}
    # The item type of a list: what its stored instances hold
    for lst in tree.iter("ViewModelInstanceList"):
        prop = props_by_id.get(lst.get("viewModelPropertyId"))
        if prop:
            prop["items"].update(i.get("viewModelId") for i in lst.iter("ViewModelInstanceListItem"))
    return vms


def load_artboards():
    boards, owner = [], {}
    for path in sorted(glob.glob(os.path.join(SHARED, "*.rml"))):
        text = open(path).read()
        ids = set(re.findall(r'\bid="([\d:]+)"', text))
        for i in ids:
            owner[i] = path
        m = re.search(r"<Artboard ([^>]*)>", text)
        if not m or 'isComponent="true"' not in m.group(1):
            continue
        attrs = dict(re.findall(r'(\w+)="([^"]*)"', m.group(1)))
        refs = set()
        for v in re.findall(r'(?:\w+Id|sourcePathIds)="([^"]+)"', text):
            refs.update(re.findall(r"\d+:\d+", v))
        boards.append({"name": attrs["name"], "file": os.path.basename(path), "id": attrs["id"],
                       "vm": attrs.get("viewModelId"), "sm": attrs.get("defaultStateMachineId"),
                       "refs": refs - ids})
    names = {b["file"]: b["name"] for b in boards}
    for b in boards:
        b["uses"] = sorted({names[os.path.basename(owner[i])] for i in b["refs"]
                            if i in owner and os.path.basename(owner[i]) in names} - {b["name"]})
    return boards


def readme_sections():
    text = open(os.path.join(ROOT, "README.md")).read()
    parts = re.split(r"^## ", text, flags=re.M)[1:]
    return {p.split("\n", 1)[0].strip(): p.split("\n", 1)[1].strip() for p in parts}


def prop_line(p, vms):
    kind = p["type"]
    if p["ref"] in vms:
        kind = "`%s`" % vms[p["ref"]]["name"]
    if p["items"]:
        kind = "list of " + " / ".join("`%s`" % vms[i]["name"] for i in sorted(p["items"]) if i in vms)
    return "| `%s` | %s | `%s` |" % (p["name"], kind, p["id"])


def snippet(b, vm):
    """A nested instance of the component with every property listed."""
    n = iter(range(1, 1000))
    out = ["```xml",
           '<NestedArtboardLayout instanceWidthScaleType="hug" instanceHeightScaleType="hug" artboardId="%s" '
           'isStateful="true" name="%s" id="X:%d">' % (b["id"], b["name"], next(n))]
    if b["sm"]:
        out.append('    <NestedStateMachine animationId="%s" id="X:%d"/>' % (b["sm"], next(n)))
    if vm:
        out.append('    <ViewModelInstance viewModelId="%s" exports="true" name="My %s" id="X:%d">'
                   % (b["vm"], b["name"], next(n)))
        for p in vm["props"]:
            tag = p["tag"].replace("ViewModelProperty", "ViewModelInstance")
            note = p["name"]
            if p["type"] == "view model":
                note += ": set propertyValue to the id of a shared instance"
            elif p["type"] == "list":
                note += ": add ViewModelInstanceListItem children"
            out.append('        <%s viewModelPropertyId="%s" id="X:%d"/>  <!-- %s -->' % (tag, p["id"], next(n), note))
        out.append("    </ViewModelInstance>")
    out += ["</NestedArtboardLayout>", "```", ""]
    return out


def main():
    vms, boards, readme = load_root(), load_artboards(), readme_sections()
    vm_board = {b["vm"]: b["name"] for b in boards}
    out = [HEADER]
    theme_id, theme = next((k, v) for k, v in vms.items() if v["global"])
    tid = {p["name"]: p["id"] for p in theme["props"]}
    out += ["## Theme (global view model)", "",
            "View model id `%s`. Settable: " % theme_id
            + ", ".join("`%s`" % t for t in tid if not t.startswith("_")) + ".", "",
            "Bind a colour in your own artboard to a token: inside its `SolidColor`, "
            '`<DataBindContext sourcePathIds="%s-<token id>" propertyKey="37"/>`.' % theme_id, "",
            "| Token | Id |", "|---|---|"] + ["| `%s` | `%s` |" % (t, i) for t, i in tid.items() if t.startswith("_")] + [""]
    for b in sorted(boards, key=lambda b: (b["name"] in SHOWCASE_ONLY, b["name"])):
        vm = vms.get(b["vm"])
        demo = b["name"] in SHOWCASE_ONLY
        head = "Source: `shared/%s` · artboard `%s`" % (b["file"], b["id"])
        if b["sm"]:
            head += " · state machine `%s`" % b["sm"]
        if vm:
            head += " · view model `%s` `%s`" % (vm["name"], b["vm"])
        out += ["## %s%s" % (b["name"], "  (Showcase demo)" if demo else ""), "", head]
        nested = set(b["uses"])
        if vm:
            for p in vm["props"]:
                for i in p["items"] | ({p["ref"]} if p["ref"] else set()):
                    if i in vm_board:
                        nested.add(vm_board[i])
        nested.discard(b["name"])
        if nested:
            out.append("Contains: " + ", ".join(sorted(nested)))
        out.append("")
        if vm:
            public = [p for p in vm["props"] if not p["name"].startswith("_") or p["type"] == "trigger"]
            if public:
                out += ["| Property | Type | Id |", "|---|---|---|"] + [prop_line(p, vms) for p in public] + [""]
        section = readme.get(b["name"]) or readme.get(vm["name"] if vm else "")
        if section:
            out += [section, ""]
        if not demo:
            out += snippet(b, vm)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write("\n".join(out).rstrip() + "\n")
    print("wrote %s: %d components" % (os.path.relpath(OUT, ROOT), len(boards)))


if __name__ == "__main__":
    main()
